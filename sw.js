/**
 * Service worker — the offline guarantee, and the freshness guarantee.
 *
 * Every file the app needs is precached on install, so once the page has been
 * opened one time it works with the radio off: no module fetch, no font, no
 * icon ever needs the network again. Games live in localStorage and never
 * touch it in the first place.
 *
 * Freshness is the harder half. GitHub Pages serves every asset from an
 * unversioned URL with a short max-age, which gives two ways to serve a stale
 * file, and both are closed here:
 *
 *   - `cache.addAll` reads through the browser's HTTP cache, so a newly named
 *     cache could be filled with the *previous* release's bytes. Every
 *     precache fetch therefore uses `cache: 'reload'`.
 *   - A worker never re-fetches a URL it has already cached, so a changed file
 *     behind an unchanged URL would live forever. PRECACHE keys each entry by
 *     a content hash, so changing a byte changes the key.
 *
 * Between them, a user never has to hard refresh to be running the current
 * build. PRECACHE is generated by tools/build-sw.mjs and checked in CI.
 */

