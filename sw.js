/** Rebuilt whenever any precached file changes, since the hashes live here. */
const CACHE = 'escalier-precache';

/** The cache key for an asset: its URL plus its content hash. */
function keyFor(url, rev) {
  return `${url}?v=${rev}`;
}

/** Assets whose absence must not cost the user offline support. */
const OPTIONAL = /\/assets\//;

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      const wanted = new Set(PRECACHE.map(([url, rev]) => new URL(keyFor(url, rev), self.location).href));

      // Only fetch what is actually new: an unchanged file keeps its entry
      // across releases, so an update costs one request per changed file.
      const existing = new Set((await cache.keys()).map((request) => request.url));

      const required = [];
      const optional = [];
      for (const [url, rev] of PRECACHE) {
        const href = new URL(keyFor(url, rev), self.location).href;
        if (existing.has(href)) continue;
        (OPTIONAL.test(url) ? optional : required).push(keyFor(url, rev));
      }

      // `reload` bypasses the HTTP cache, so a short max-age cannot hand us
      // the previous release's body under the new hash.
      await Promise.all(
        required.map(async (target) => {
          const response = await fetch(new Request(target, { cache: 'reload' }));
          if (!response.ok) throw new Error(`precache failed: ${target} (${response.status})`);
          await cache.put(target, response);
        })
      );
      await Promise.allSettled(
        optional.map(async (target) => {
          const response = await fetch(new Request(target, { cache: 'reload' }));
          if (response.ok) await cache.put(target, response);
        })
      );

      // Superseded entries are NOT removed here. Installing happens while the
      // previous worker is still serving pages, and it still needs its own
      // (now superseded) entries — deleting them during install would break
      // the running app for any user who is offline between install and
      // activate. Cleanup belongs in activate, once nothing is using them.
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Caches from the older, version-named scheme.
      const keys = await caches.keys();
      await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)));

      // Now that the previous worker has stopped, drop the entries it was
      // using for files that have since changed or gone away.
      const cache = await caches.open(CACHE);
      const wanted = new Set(PRECACHE.map(([url, rev]) => new URL(keyFor(url, rev), self.location).href));
      await Promise.all(
        (await cache.keys()).map(async (request) => {
          if (!wanted.has(request.url)) await cache.delete(request);
        })
      );

      await self.clients.claim();
    })()
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

/** Look an incoming request up against the hashed precache. */
async function matchPrecached(cache, pathname) {
  const scopePath = new URL('./', self.location).pathname;
  const relative = pathname.startsWith(scopePath) ? `./${pathname.slice(scopePath.length)}` : pathname;
  const entry = PRECACHE.find(([url]) => url === relative || (relative === './' && url === './'));
  if (!entry) return null;
  return cache.match(keyFor(entry[0], entry[1]));
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Navigations resolve to the app shell: routing is client-side and the
  // fragment (where shared games travel) never reaches the network.
  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const root = new URL('./', self.location);

        // Serving the shell for a deeper path would leave its relative module
        // URLs resolving against that path, so the page would load and never
        // boot. Send the browser to the root instead — it carries the fragment
        // across, so a shared game still arrives.
        if (url.pathname !== root.pathname && url.pathname !== `${root.pathname}index.html`) {
          return Response.redirect(`${root.href}${url.search}`, 302);
        }

        const cache = await caches.open(CACHE);
        const shell = await matchPrecached(cache, new URL('./index.html', self.location).pathname);
        if (shell) return shell;
        try {
          return await fetch(request);
        } catch {
          return new Response('<h1>Offline</h1>', { status: 503, headers: { 'Content-Type': 'text/html' } });
        }
      })()
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const cached = await matchPrecached(cache, url.pathname);
      if (cached) return cached;

      // Not one of ours: go to the network, and do not grow the cache with it.
      return fetch(request);
    })()
  );
});
